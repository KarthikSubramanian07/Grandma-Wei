# Font pipeline: run with `python scripts/fonts.py <dir with Google Fonts TTFs> apps/web/public/fonts packages/card/fonts packages/card/src/seal.ts` (needs fonttools + brotli).
import sys, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

src, out_web, out_card, out_seal = sys.argv[1:5]
os.makedirs(out_web, exist_ok=True); os.makedirs(out_card, exist_ok=True)
LATIN = "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+2010-2027,U+2030-203A,U+2044,U+20AC,U+2122,U+2190-2193,U+2212,U+00D7"

def do_subset(font, flavor=None):
    opts = subset.Options(); opts.layout_features = ["kern", "liga", "calt", "pnum", "tnum", "lnum", "onum"]
    opts.flavor = flavor; opts.name_IDs = ["*"]; opts.notdef_outline = True
    s = subset.Subsetter(opts); s.populate(unicodes=subset.parse_unicodes(LATIN)); s.subset(font)
    return font

def rename(font, family):
    """Give card fonts plain family names so the renderer matches them exactly."""
    table = font["name"]
    for rec in list(table.names):
        if rec.nameID in (1, 16, 21):
            table.setName(family, rec.nameID, rec.platformID, rec.platEncID, rec.langID)
        if rec.nameID in (4,):
            table.setName(family + " " + str(rec.toUnicode()).split()[-1], rec.nameID, rec.platformID, rec.platEncID, rec.langID)

def save(font, path, flavor=None):
    font.flavor = flavor; font.save(path); print(path, os.path.getsize(path))

# Web: variable woff2, Latin only.
for name, f in [("newsreader", "Newsreader%5Bopsz,wght%5D.ttf"), ("newsreader-italic", "Newsreader-Italic%5Bopsz,wght%5D.ttf"), ("geist-mono", "GeistMono%5Bwght%5D.ttf"), ("kalam", "Kalam-Regular.ttf"), ("kalam-bold", "Kalam-Bold.ttf")]:
    save(do_subset(TTFont(os.path.join(src, f))), os.path.join(out_web, name + ".woff2"), "woff2")

# Card: static TTF instances for the server-side renderer.
for name, f, axes in [
    ("Newsreader-Light", "Newsreader%5Bopsz,wght%5D.ttf", {"wght": 300, "opsz": 72}),
    ("Newsreader-Regular", "Newsreader%5Bopsz,wght%5D.ttf", {"wght": 400, "opsz": 18}),
    ("Newsreader-Medium", "Newsreader%5Bopsz,wght%5D.ttf", {"wght": 500, "opsz": 24}),
    ("Newsreader-Italic", "Newsreader-Italic%5Bopsz,wght%5D.ttf", {"wght": 400, "opsz": 36}),
    ("GeistMono-Regular", "GeistMono%5Bwght%5D.ttf", {"wght": 400}),
    ("GeistMono-Medium", "GeistMono%5Bwght%5D.ttf", {"wght": 500}),
]:
    font = instancer.instantiateVariableFont(TTFont(os.path.join(src, f)), axes)
    rename(font, "GW Mono" if name.startswith("Geist") else "GW Serif")
    save(do_subset(font), os.path.join(out_card, name + ".ttf"))
kalam = TTFont(os.path.join(src, "Kalam-Bold.ttf")); rename(kalam, "GW Hand")
save(do_subset(kalam), os.path.join(out_card, "Kalam-Bold.ttf"))

# The seal: the character 魏 (Wei) as an SVG path in a 1000-unit box, heavy weight.
cjk = instancer.instantiateVariableFont(TTFont(os.path.join(src, "NotoSerifSC.ttf")), {"wght": 800})
gs = cjk.getGlyphSet(); name = cjk.getBestCmap()[ord("魏")]
upm = cjk["head"].unitsPerEm
pen = SVGPathPen(gs)
g = gs[name]
# Flip y and center in the em box.
tp = TransformPen(pen, (1, 0, 0, -1, 0, cjk["hhea"].ascent))
g.draw(tp)
with open(out_seal, "w") as fh:
    fh.write(f'// Generated by scripts/fonts.py from Noto Serif SC (OFL). The character 魏, Grandma Wei\'s seal.\nexport const SEAL_UPM = {upm};\nexport const SEAL_ASCENT = {cjk["hhea"].ascent};\nexport const SEAL_ADVANCE = {g.width};\nexport const SEAL_PATH = "{pen.getCommands()}";\n')
print(out_seal, os.path.getsize(out_seal))

# Character advance widths (fraction of the em) for wrapping text on the card.
import json
metrics = {}
for name in ["Newsreader-Light", "Newsreader-Regular", "Newsreader-Medium", "Newsreader-Italic", "GeistMono-Regular", "GeistMono-Medium", "Kalam-Bold"]:
    f = TTFont(os.path.join(out_card, name + ".ttf"))
    upm = f["head"].unitsPerEm; cmap = f.getBestCmap(); hmtx = f["hmtx"]
    widths = {}
    for cp in list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2014, 0x2013, 0x2019, 0x2018, 0x201C, 0x201D, 0x2026, 0x2192, 0x2212, 0xD7]:
        if cp in cmap:
            widths[chr(cp)] = round(hmtx[cmap[cp]][0] / upm, 4)
    metrics[name] = {"fallback": round(sum(widths.values()) / len(widths), 4), "w": widths}
    f2 = f
    print(name, "family:", f["name"].getDebugName(1), "| sub:", f["name"].getDebugName(2), "| weight:", f["OS/2"].usWeightClass)
with open(os.path.join(os.path.dirname(out_seal), "metrics.ts"), "w") as fh:
    fh.write("// Generated by scripts/fonts.py: advance widths as a fraction of the em, for wrapping card text.\n")
    fh.write("export const METRICS: Record<string, { fallback: number; w: Record<string, number> }> = " + json.dumps(metrics, ensure_ascii=False) + ";\n")
